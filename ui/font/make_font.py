#!/usr/bin/env python3
"""Builds the Sproto Pixel bitmap fonts: an original, hand-drawn early-90s
console-style typeface in two weights.

  python3 ui/font/make_font.py            (run from anywhere; needs Pillow)

Writes PNG glyph sheets plus BMFont descriptors (.fnt) to ui/font/src/. The
game loads those directly (src/runtime/font.ts).

Fonts:
  sproto_small.png/.fnt          5x7 glyphs, 1 px strokes, plain white (menus)
  sproto_small_outline.png/.fnt  same glyphs with a baked 1 px dark outline
                                 (labels drawn over gameplay)
  sproto_bold.png/.fnt           7x7 glyphs, 2 px stems, dark outline, white
                                 body with a soft shade (tint with font_color)
  sproto_bold_gold.png/.fnt      same, with a baked gold gradient (HUD labels)

Lowercase letters reuse the capitals, except 'x', which is a small
multiplication sign for counters such as "x 3" (U+00D7 maps to it too).
Every glyph below was drawn for this project; '#' is ink, '.' is empty.
"""

