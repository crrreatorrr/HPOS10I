# Every font must have at least these (checked by tests/ui/test_font.gd too).
REQUIRED = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:-.!?/x'"

OUTLINE = (24, 20, 48, 255)  # dark navy, never pure black
WHITE_SHADE = [(255, 255, 255), (255, 255, 255), (255, 255, 255), (255, 255, 255),
               (255, 255, 255), (226, 230, 242), (198, 206, 226)]
GOLD_RAMP = [(255, 248, 196), (255, 236, 112), (255, 222, 64), (252, 200, 40),
             (246, 172, 30), (236, 140, 22), (218, 108, 18)]

COLUMNS = 16


def validate(glyphs, name):
    for ch, rows in glyphs.items():
        assert len(rows) == 7, "%s %r: needs 7 rows" % (name, ch)
        widths = {len(r) for r in rows}
        assert len(widths) == 1, "%s %r: ragged rows" % (name, ch)
        assert set("".join(rows)) <= set("#."), "%s %r: bad pixel" % (name, ch)
    for ch in REQUIRED:
        assert ch in glyphs, "%s: missing required glyph %r" % (name, ch)


def build(glyphs, name, face, outline, ramp, space_advance):
    """Draws one sheet and its .fnt. Returns {char: (x, y, w, h)}."""
    pad = 1 if outline else 0
    max_w = max(len(r[0]) for r in glyphs.values())
    cell_w = max_w + 2 * pad + 1
    cell_h = 7 + 2 * pad + 1
    order = sorted(glyphs.keys(), key=ord)
    rows_needed = (len(order) + COLUMNS - 1) // COLUMNS
    sheet_w = COLUMNS * cell_w
    sheet_h = rows_needed * cell_h
    img = Image.new("RGBA", (sheet_w, sheet_h), (0, 0, 0, 0))
    px = img.load()
    rects = {}
    for i, ch in enumerate(order):
        rows = glyphs[ch]
        w = len(rows[0])
        ox = (i % COLUMNS) * cell_w
        oy = (i // COLUMNS) * cell_h
        ink = {(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == "#"}
        if outline:
            for (x, y) in ink:
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        p = (x + dx, y + dy)
                        if p not in ink:
                            px[ox + pad + p[0], oy + pad + p[1]] = OUTLINE
        for (x, y) in ink:
            r, g, b = ramp[y]
            px[ox + pad + x, oy + pad + y] = (r, g, b, 255)
        rects[ch] = (ox, oy, w + 2 * pad, 7 + 2 * pad)
    png = name + ".png"
    img.save(os.path.join(SRC, png))

    # Line metrics: the body sits on rows [pad, pad + 7); baseline below it.
    base = 7 + pad
    line_height = 7 + 2 * pad + 2
    chars = []
    for ch in order:
        x, y, w, h = rects[ch]
        chars.append((ord(ch), x, y, w, h, -pad, 0, w - 2 * pad + 1))
    # Lowercase reuses the capitals ('x' keeps its own small multiplier glyph).
    for ch in "abcdefghijklmnopqrstuvwyz":
        x, y, w, h = rects[ch.upper()]
        chars.append((ord(ch), x, y, w, h, -pad, 0, w - 2 * pad + 1))
    x, y, w, h = rects["x"]
    chars.append((0xD7, x, y, w, h, -pad, 0, w - 2 * pad + 1))
    chars.append((32, 0, 0, 0, 0, 0, 0, space_advance))
    chars.sort()

    lines = [
        'info face="%s" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 '
        'smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0' % face,
        "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 "
        "alphaChnl=0 redChnl=0 greenChnl=0 blueChnl=0" % (line_height, base, sheet_w, sheet_h),
        'page id=0 file="%s"' % png,
        "chars count=%d" % len(chars),
    ]
    for (cid, x, y, w, h, xo, yo, adv) in chars:
        lines.append("char id=%d x=%d y=%d width=%d height=%d xoffset=%d yoffset=%d "
                     "xadvance=%d page=0 chnl=15" % (cid, x, y, w, h, xo, yo, adv))
    with open(os.path.join(SRC, name + ".fnt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return rects


def main():
    validate(SMALL, "small")
    validate(BOLD, "bold")
    plain = [(255, 255, 255)] * 7
    build(SMALL, "sproto_small", "Sproto Pixel Small", False, plain, 4)
    build(SMALL, "sproto_small_outline", "Sproto Pixel Small Outline", True, plain, 4)
    build(BOLD, "sproto_bold", "Sproto Pixel Bold", True, WHITE_SHADE, 5)
    build(BOLD, "sproto_bold_gold", "Sproto Pixel Bold Gold", True, GOLD_RAMP, 5)
    print("font sources written to", SRC)


if __name__ == "__main__":
    main()
